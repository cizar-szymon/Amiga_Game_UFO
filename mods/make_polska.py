"""Builds the Polska mod (Poland and Warsaw on the UFO globe) from the
standard xcom1 rulesets of the OpenXcom tree the port is built from.

The globe's polylines and a region's missionZones are replaced as a whole by
a mod (RuleGlobe::load, RuleRegion::load), so the mod carries the full lists
of the original with Poland's lines and Warsaw added.

usage: python make_polska.py <OpenXcom tree>/bin/standard/xcom1 <out dir>
"""
import os
import sys

src, out = sys.argv[1], sys.argv[2]


def section(path, start_marker, end_marker):
    lines = open(path, encoding='utf-8').read().split('\n')
    i = next(k for k, l in enumerate(lines) if l.startswith(start_marker))
    j = i + 1
    while j < len(lines) and not any(lines[j].startswith(m) for m in end_marker):
        j += 1
    return lines[i:j]


# globe polylines: every "    - [..]" line under "  polylines:"
globe = open(os.path.join(src, 'globe.rul'), encoding='utf-8').read().split('\n')
pi = globe.index('  polylines:')
poly = []
for l in globe[pi + 1:]:
    if l.startswith('    - ['):
        poly.append(l)
    else:
        break
assert len(poly) > 20, len(poly)

# Poland's southern (Czech, Slovak) and eastern (Ukraine, Belarus, Lithuania)
# border and the border with the Kaliningrad oblast; the western one is
# Germany's eastern line, already in the list. lon, -lat, in 1/8 degree.
poland = [15, -50.875, 16.25, -50.625, 16.5, -50.25, 17.625, -50.25, 18, -49.875,
          18.875, -49.5, 19.375, -49.625, 20.25, -49.375, 21.375, -49.375, 22.625, -49.125,
          23.625, -50.375, 24.125, -50.875, 23.625, -51.625, 23.625, -52.625, 23.875, -53,
          23.5, -54, 22.75, -54.375, 19.625, -54.375]
poly.append('    - [' + ', '.join(('%g' % v) for v in poland) + ']')

# Europe's mission zones, with Warsaw in the city zone (the one with Berlin)
regions = open(os.path.join(src, 'regions.rul'), encoding='utf-8').read().split('\n')
ei = regions.index('  - type: STR_EUROPE')
mz = regions.index('    missionZones:', ei)
zones = []
for l in regions[mz + 1:]:
    if l.startswith('      ') or l.strip() == '':
        if l.strip() == '':
            break
        zones.append(l)
    else:
        break
berlin = [k for k, l in enumerate(zones) if 'STR_BERLIN' in l]
assert len(berlin) == 1
zones.insert(berlin[0] + 1, '        - [21, 21, -52.25, -52.25, -1, STR_WARSAW]')

rul = []
rul.append('# Polska: Poland and Warsaw on the globe. Generated by make_polska.py from')
rul.append('# the standard xcom1 rulesets - edit the script, not this file.')
rul.append('countries:')
rul.append('  - type: STR_POLAND')
rul.append('    fundingBase: 0     # on the map only: no funding, the game unchanged')
rul.append('    fundingCap: 0')
rul.append('    labelLon: 19      # north-west of Warsaw: at 19.25/52 it sat under the city name')
rul.append('    labelLat: -53.25')
rul.append('    areas:')
rul.append('      - [15, 24.25, -54.875, -49]')
rul.append('regions:')
rul.append('  - type: STR_EUROPE')
rul.append('    missionZones:')
rul.extend(zones)
rul.append('globe:')
rul.append('  polylines:')
rul.extend(poly)
rul.append('extraStrings:')
for lang, country, city in (('en-US', 'POLAND', 'Warsaw'), ('en-GB', 'POLAND', 'Warsaw'),
                            ('pl-PL', 'POLSKA', 'Warszawa')):
    rul.append('  - type: %s' % lang)
    rul.append('    strings:')
    rul.append('      STR_POLAND: "%s"' % country)
    rul.append('      STR_WARSAW: "%s"' % city)
rul.append('')

os.makedirs(out, exist_ok=True)
with open(os.path.join(out, 'Polska.rul'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(rul))
with open(os.path.join(out, 'metadata.yml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('name: "Polska"\n'
            'version: 1.0\n'
            'description: "Poland (no funding) and Warsaw on the globe."\n'
            'author: AmiXcom\n'
            '\n'
            'master: xcom1\n')
print('polylines %d, zones lines %d -> %s' % (len(poly), len(zones), out))
